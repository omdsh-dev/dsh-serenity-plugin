/**
 * tools/trajectory-self-docs.ts — 「一条认知轨迹如何描述自己」的**手册正文**
 *
 * ## 为什么这一章单独存在（owner 2026-10-20 原话）
 *
 * > 「例如某个认知轨迹想设定自己是**常驻**的，想给自己做**轨迹约束**，
 * >   这种**说明性的内容**有吗，在哪里，**这是很重要的内容**，
 * >   是认知轨迹感知理解这些**边界的重要手册**」
 *
 * ⇒ 此前「描述自己」与「限制自己」被混成一章（`trajectory-constraint`），
 *   而那两件事的**读者与前提完全不同**：
 *
 * | 面 | 谁需要 | 性质 |
 * |---|---|---|
 * | **描述自己**（我是谁、我擅长什么、我是否欢迎来麻烦我） | **所有轨迹** | 常态 |
 * | **限制自己**（工具白名单、模型、MSM 白名单） | 只有需要限权的轨迹 | 特例 |
 *
 * ⇒ 把「描述」独立成章。**普通轨迹不必为了写一段自述而变成受约束的轨迹** ——
 *   这是本章存在的**唯一理由**，也是 D173「常驻 = 自我声明」的落点。
 *
 * ## 归属（D23）
 * 机制在 ACC（有哪些载体文件、字段叫什么、怎么被读、何时生效）；
 * **内容在 CCC**（这条轨迹具体写什么 —— 它的章程与自述是它自己的知识）。
 *
 * ## 与 `trajectory-constraint` 章的分工（一个内容一个正文入口）
 * 本章 = **声明面（我是什么）**；那一章 = **约束面（我被限成什么）**。
 * 两章互指，但**不复制**对方正文（本仓 v1.75.0 的指针纪律）。
 */

/**
 * 三个**自我描述的载体**，按「谁读它、何时生效」区分。
 *
 * 🔴 这是本章的**骨架**：读者必须一眼看出"我想改的那件事，该写进哪个文件"。
 * 三者的**主语不同**，所以不能合并；合并会让"写一句话"变成"改一份配置"。
 */
const CARRIERS = `── 三个载体：想改哪件事，就写进哪个文件 ──

  <trajectory>/SESSION.md     ← 我的**身体**（认知轨迹本体；持久、永不移动）
  <trajectory>/PROMPT.md      ← 我的**章程**（我是谁、按什么工作；**所有轨迹都可以有**）
  <trajectory>/trajectory.json ← 我的**声明**（结构化字段；有它才成为"轨迹约束"，见下）

  ⚠️ 三者主语相同（都是这条轨迹）、生命周期相同（随 git 走）、写入频率相同（人偶尔改）
  ⇒ 这正是它们**该分开而不该合并**的理由：每一项都对应一种**不同的意图**。`

/**
 * 章程（PROMPT.md）——最常被忽略的一项。
 *
 * 🔴 为什么值得单列：`PROMPT.md` 是**所有轨迹**都能有的，而很多轨迹至今没写；
 * 它们因此只能拿到 ACC 的通用身份，拿不到"我是谁、这件事我按什么规矩做"。
 */
const CHARTER = `── PROMPT.md：我的章程（推荐所有轨迹都写）──

  写什么：我这名认知轨迹的**身份与工作方式** —— 我负责什么、我的判断依据是什么、
          我的边界在哪、我怎么跟其他轨迹协作。
  谁读它：**只有绑定在我身上的会话**读到它（作为系统提示词的一个独立段）。
  何时生效：**保存即生效**（按 mtime 热重载，无需重启、无需 rebuild）。
  没有它会怎样：不报错。我拿到的是 ACC 的通用身份 —— 普通轨迹的常态，不是缺陷。

  ⚠️ 与 SESSION.md 的分工（别写重了）：
     SESSION.md = **发生了什么**（日志、决策、当前状态）
     PROMPT.md  = **我是谁、怎么工作**（章程；很少改，改了就改变行为）`

/**
 * 常驻声明（D173）—— owner 2026-10-20 澄清的语义。
 *
 * 🔴 这是本章最容易被误解的一格，必须把「不是」写在前面。
 */
const RESIDENT = `── 常驻：自己声明"欢迎别人来麻烦我"（trajectory.json 的 resident 字段）──

  🔴 先排除一个误解：**常驻不是资源状态**。
     它不是"永不休眠"、不是"常驻内存"、不是"不许销毁我的会话"。
     一条轨迹**永远存在**（没有生命周期），常驻与否都不改变这一点。

  那它是什么：**我对自己用途的公开声明** —— "我在这儿、我擅长什么、欢迎来麻烦我"。
     别的轨迹要找人干活时，先查这份名单，而不是靠猜谁可能懂。

  写法：
    { "resident": { "serves": "一句话说清我擅长什么、能帮上什么忙" } }

  ⚠️ 两个门槛，缺一不可：
     ① 写了 \`resident\` ⇒ 我进得了别人的候选名单（**可被发现**）
     ② \`serves\` 非空 ⇒ 别人读了这句话能判断"这事是不是该找你"（**可被判断**）
     只写半个（有字段、没 serves）等于把自己挂上去却不说能干什么 —— 那比不写更坏，
     因为别人会来问，然后发现问错了人。

  谁能看见：通过 cognitive_trajectory 的常驻名单动作按需查询。
     **它不进系统提示词**（不占每个请求的 token）—— 只在有人真的要找人时才读。
     这是 owner 2026-10-20 的裁决：说明类信息按需取，不常驻在上下文里。`

/**
 * 约束面 —— 只讲"怎么开启"，正文指向另一章。
 */
const CONSTRAINT_POINTER = `── 想限制自己（白名单 / 模型 / 纪律参与项）──

  写 \`trajectory.json\` 即成为**轨迹约束**（判据是**文件存在**，不是某个字段存在）。
  删掉它 ⇒ 当场退回普通轨迹。

  ⚠️ 一个必须知道的连带后果：**写 trajectory.json 会把我变成受约束的轨迹**。
     所以如果你只想"描述自己"（章程、常驻），**不需要**建这个文件 ——
     章程走 PROMPT.md；常驻字段确实也在这个文件里，但**只写 resident、不写 tools/msms**
     时，白名单为空 = 不收窄任何工具面（见下一章"两个默认"）。

  schema、双白名单、纪律参与项的完整说明 → container_admin config docs trajectory-constraint`

